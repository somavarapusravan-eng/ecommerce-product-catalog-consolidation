USE DATABASE PRODUCT_CATALOG_DB;
USE SCHEMA BRONZE;
USE WAREHOUSE PRODUCT_CATALOG_WH;

--CREATE FILE FORMAT CSV
CREATE OR REPLACE FILE FORMAT PRODUCT_CSV_FORMAT
TYPE = CSV
SKIP_HEADER = 1
FIELD_OPTIONALLY_ENCLOSED_BY = '"'
EMPTY_FIELD_AS_NULL = TRUE
TRIM_SPACE = TRUE
NULL_IF = ('NULL', 'null');


--  CREATE INTERNAL STAGE
CREATE OR REPLACE STAGE PRODUCT_CATALOG_STAGE
FILE_FORMAT = PRODUCT_CSV_FORMAT;


-- ADDED stylehaus_products.CSV AND urbanthread_products.CSV to stage
LIST @PRODUCT_CATALOG_DB.BRONZE.PRODUCT_CATALOG_STAGE;


-- COPY CSV DATA TO RAW TABLES
COPY INTO PRODUCT_CATALOG_DB.BRONZE.STYLEHAUS_RAW
(
    SKU,
    PRODUCT_NAME,
    BRAND,
    CATEGORY,
    DESCRIPTION,
    PRICE,
    COLOR,
    SIZE,
    MATERIAL,
    IN_STOCK,
    UPDATED_AT
)
FROM @PRODUCT_CATALOG_DB.BRONZE.PRODUCT_CATALOG_STAGE
FILES = ('stylehaus_products.csv')
FILE_FORMAT = (
    FORMAT_NAME = 'PRODUCT_CATALOG_DB.BRONZE.PRODUCT_CSV_FORMAT'
)
ON_ERROR = 'ABORT_STATEMENT';




COPY INTO PRODUCT_CATALOG_DB.BRONZE.URBANTHREAD_RAW
(
    PRODUCT_CODE,
    TITLE,
    MANUFACTURER,
    TYPE,
    DETAILS,
    RETAIL_PRICE,
    COLOUR,
    DIMENSIONS,
    FABRIC,
    AVAILABILITY,
    LAST_MODIFIED
)
FROM @PRODUCT_CATALOG_DB.BRONZE.PRODUCT_CATALOG_STAGE
FILES = ('urbanthread_products.csv')
FILE_FORMAT = (
    FORMAT_NAME = 'PRODUCT_CATALOG_DB.BRONZE.PRODUCT_CSV_FORMAT'
)
ON_ERROR = 'ABORT_STATEMENT';




-- VALIDATE COUNTS
SELECT 'STYLEHAUS' AS SOURCE, COUNT(*) AS TOTAL
FROM PRODUCT_CATALOG_DB.BRONZE.STYLEHAUS_RAW
UNION ALL
SELECT 'URBANTHREAD', COUNT(*)
FROM PRODUCT_CATALOG_DB.BRONZE.URBANTHREAD_RAW;