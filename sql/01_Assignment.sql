-- CREATE DB, SCHEMA, WH AND TABLE STRUCTURES
CREATE DATABASE PRODUCT_CATALOG_DB;
USE DATABASE PRODUCT_CATALOG_DB;

CREATE WAREHOUSE PRODUCT_CATALOG_WH
WITH
    WAREHOUSE_SIZE = 'X-SMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE;

USE WAREHOUSE PRODUCT_CATALOG_WH;


CREATE SCHEMA IF NOT EXISTS BRONZE;
CREATE SCHEMA IF NOT EXISTS SILVER;
CREATE SCHEMA IF NOT EXISTS GOLD;
CREATE SCHEMA IF NOT EXISTS AUDIT;


-- CREATE TABLES
CREATE OR REPLACE TABLE BRONZE.STYLEHAUS_RAW (
    SKU             VARCHAR,
    PRODUCT_NAME    VARCHAR,
    BRAND           VARCHAR,
    CATEGORY        VARCHAR,
    DESCRIPTION     VARCHAR,
    PRICE           VARCHAR,
    COLOR           VARCHAR,
    SIZE            VARCHAR,
    MATERIAL        VARCHAR,
    IN_STOCK        VARCHAR,
    UPDATED_AT      VARCHAR,
    INGESTED_AT     TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);



CREATE OR REPLACE TABLE BRONZE.URBANTHREAD_RAW (
    PRODUCT_CODE    VARCHAR,
    TITLE           VARCHAR,
    MANUFACTURER    VARCHAR,
    TYPE            VARCHAR,
    DETAILS         VARCHAR,
    RETAIL_PRICE    VARCHAR,
    COLOUR          VARCHAR,
    DIMENSIONS      VARCHAR,
    FABRIC          VARCHAR,
    AVAILABILITY    VARCHAR,
    LAST_MODIFIED   VARCHAR,
    INGESTED_AT     TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);




-- VALIDATE
SHOW DATABASES LIKE 'PRODUCT_CATALOG_DB';

SHOW SCHEMAS IN DATABASE PRODUCT_CATALOG_DB;

SHOW TABLES IN SCHEMA PRODUCT_CATALOG_DB.BRONZE;


