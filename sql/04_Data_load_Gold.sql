base AS (
    SELECT
        COALESCE(
            pm.PRODUCT_GROUP_ID,
            p.SOURCE_SYSTEM || ':' || p.SOURCE_PRODUCT_ID
        ) AS PRODUCT_ID,
        p.*
    FROM PRODUCT_CATALOG_DB.SILVER.PRODUCTS_STANDARDIZED p
    LEFT JOIN pair_map pm
        ON p.SOURCE_SYSTEM = pm.SOURCE_SYSTEM
       AND p.SOURCE_PRODUCT_ID = pm.SOURCE_PRODUCT_ID
)

SELECT
    PRODUCT_ID,

    GET(ARRAY_AGG(
        IFF(PRODUCT_NAME IS NOT NULL,
            OBJECT_CONSTRUCT('value', PRODUCT_NAME, 'source', SOURCE_SYSTEM),
            NULL)
    ) WITHIN GROUP (
        ORDER BY LENGTH(PRODUCT_NAME) DESC, UPDATED_AT DESC NULLS LAST
    ), 0):value::STRING AS PRODUCT_NAME,

    GET(ARRAY_AGG(
        IFF(BRAND IS NOT NULL,
            OBJECT_CONSTRUCT('value', BRAND, 'source', SOURCE_SYSTEM),
            NULL)
    ) WITHIN GROUP (ORDER BY UPDATED_AT DESC NULLS LAST), 0):value::STRING AS BRAND,
    GET(ARRAY_AGG(
        IFF(BRAND IS NOT NULL,
            OBJECT_CONSTRUCT('value', BRAND, 'source', SOURCE_SYSTEM),
            NULL)
    ) WITHIN GROUP (ORDER BY UPDATED_AT DESC NULLS LAST), 0):source::STRING AS BRAND_SOURCE,

    GET(ARRAY_AGG(
        IFF(CATEGORY IS NOT NULL,
            OBJECT_CONSTRUCT('value', CATEGORY, 'source', SOURCE_SYSTEM),
            NULL)
    ) WITHIN GROUP (ORDER BY UPDATED_AT DESC NULLS LAST), 0):value::STRING AS CATEGORY,
    GET(ARRAY_AGG(
        IFF(CATEGORY IS NOT NULL,
            OBJECT_CONSTRUCT('value', CATEGORY, 'source', SOURCE_SYSTEM),
            NULL)
    ) WITHIN GROUP (ORDER BY UPDATED_AT DESC NULLS LAST), 0):source::STRING AS CATEGORY_SOURCE,

    GET(ARRAY_AGG(
        IFF(DESCRIPTION IS NOT NULL,
            OBJECT_CONSTRUCT('value', DESCRIPTION, 'source', SOURCE_SYSTEM),
            NULL)
    ) WITHIN GROUP (
        ORDER BY LENGTH(DESCRIPTION) DESC, UPDATED_AT DESC NULLS LAST
    ), 0):value::STRING AS DESCRIPTION,
    GET(ARRAY_AGG(
        IFF(DESCRIPTION IS NOT NULL,
            OBJECT_CONSTRUCT('value', DESCRIPTION, 'source', SOURCE_SYSTEM),
            NULL)
    ) WITHIN GROUP (
        ORDER BY LENGTH(DESCRIPTION) DESC, UPDATED_AT DESC NULLS LAST
    ), 0):source::STRING AS DESCRIPTION_SOURCE,

    GET(ARRAY_AGG(
        IFF(PRICE IS NOT NULL,
            OBJECT_CONSTRUCT('value', PRICE, 'source', SOURCE_SYSTEM),
            NULL)
    ) WITHIN GROUP (ORDER BY PRICE ASC, UPDATED_AT DESC NULLS LAST), 0):value::NUMBER(12,2) AS PRICE,
    GET(ARRAY_AGG(
        IFF(PRICE IS NOT NULL,
            OBJECT_CONSTRUCT('value', PRICE, 'source', SOURCE_SYSTEM),
            NULL)
    ) WITHIN GROUP (ORDER BY PRICE ASC, UPDATED_AT DESC NULLS LAST), 0):source::STRING AS PRICE_SOURCE,

    GET(ARRAY_AGG(
        IFF(COLOR IS NOT NULL,
            OBJECT_CONSTRUCT('value', COLOR, 'source', SOURCE_SYSTEM),
            NULL)
    ) WITHIN GROUP (ORDER BY UPDATED_AT DESC NULLS LAST), 0):value::STRING AS COLOR,
    GET(ARRAY_AGG(
        IFF(COLOR IS NOT NULL,
            OBJECT_CONSTRUCT('value', COLOR, 'source', SOURCE_SYSTEM),
            NULL)
    ) WITHIN GROUP (ORDER BY UPDATED_AT DESC NULLS LAST), 0):source::STRING AS COLOR_SOURCE,

    GET(ARRAY_AGG(
        IFF(SIZE IS NOT NULL,
            OBJECT_CONSTRUCT('value', SIZE, 'source', SOURCE_SYSTEM),
            NULL)
    ) WITHIN GROUP (ORDER BY UPDATED_AT DESC NULLS LAST), 0):value::STRING AS SIZE,
    GET(ARRAY_AGG(
        IFF(SIZE IS NOT NULL,
            OBJECT_CONSTRUCT('value', SIZE, 'source', SOURCE_SYSTEM),
            NULL)
    ) WITHIN GROUP (ORDER BY UPDATED_AT DESC NULLS LAST), 0):source::STRING AS SIZE_SOURCE,

    GET(ARRAY_AGG(
        IFF(MATERIAL IS NOT NULL,
            OBJECT_CONSTRUCT('value', MATERIAL, 'source', SOURCE_SYSTEM),
            NULL)
    ) WITHIN GROUP (ORDER BY UPDATED_AT DESC NULLS LAST), 0):value::STRING AS MATERIAL,
    GET(ARRAY_AGG(
        IFF(MATERIAL IS NOT NULL,
            OBJECT_CONSTRUCT('value', MATERIAL, 'source', SOURCE_SYSTEM),
            NULL)
    ) WITHIN GROUP (ORDER BY UPDATED_AT DESC NULLS LAST), 0):source::STRING AS MATERIAL_SOURCE,

    GET(ARRAY_AGG(
        IFF(IN_STOCK IS NOT NULL,
            OBJECT_CONSTRUCT('value', IN_STOCK, 'source', SOURCE_SYSTEM),
            NULL)
    ) WITHIN GROUP (ORDER BY UPDATED_AT DESC NULLS LAST), 0):value::BOOLEAN AS IN_STOCK,
    GET(ARRAY_AGG(
        IFF(IN_STOCK IS NOT NULL,
            OBJECT_CONSTRUCT('value', IN_STOCK, 'source', SOURCE_SYSTEM),
            NULL)
    ) WITHIN GROUP (ORDER BY UPDATED_AT DESC NULLS LAST), 0):source::STRING AS IN_STOCK_SOURCE,

    MAX(UPDATED_AT) AS UPDATED_AT,
    COUNT(*) AS SOURCE_RECORD_COUNT,
    LISTAGG(DISTINCT SOURCE_SYSTEM, ', ') AS SOURCE_SYSTEMS

FROM base
GROUP BY PRODUCT_ID;



