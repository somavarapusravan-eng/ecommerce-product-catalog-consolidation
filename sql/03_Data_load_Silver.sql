USE DATABASE PRODUCT_CATALOG_DB;
USE SCHEMA SILVER;


-- CREATE A STANDARD TABLE COL NAMES AND FORMATTING
CREATE OR REPLACE TABLE PRODUCTS_STANDARDIZED AS
SELECT
    'STYLEHAUS' AS SOURCE_SYSTEM,
    SKU AS SOURCE_PRODUCT_ID,
    TRIM(PRODUCT_NAME) AS PRODUCT_NAME,
    TRIM(BRAND) AS BRAND,
    INITCAP(TRIM(CATEGORY)) AS CATEGORY,
    TRIM(DESCRIPTION) AS DESCRIPTION,
    TRY_TO_DECIMAL(PRICE, 10, 2) AS PRICE,
    INITCAP(TRIM(COLOR)) AS COLOR,
    UPPER(TRIM(SIZE)) AS SIZE,
    INITCAP(TRIM(MATERIAL)) AS MATERIAL,
    CASE
        WHEN UPPER(TRIM(IN_STOCK)) IN ('TRUE', 'YES', '1', 'IN STOCK')
        THEN TRUE
        WHEN UPPER(TRIM(IN_STOCK)) IN ('FALSE', 'NO', '0', 'OUT OF STOCK')
        THEN FALSE
        ELSE NULL
    END AS IN_STOCK,
    TRY_TO_TIMESTAMP_NTZ(UPDATED_AT) AS UPDATED_AT,
    CURRENT_TIMESTAMP() AS PROCESSED_AT

FROM PRODUCT_CATALOG_DB.BRONZE.STYLEHAUS_RAW

UNION ALL

SELECT
    'URBANTHREAD' AS SOURCE_SYSTEM,
    PRODUCT_CODE AS SOURCE_PRODUCT_ID,
    TRIM(TITLE) AS PRODUCT_NAME,
    TRIM(MANUFACTURER) AS BRAND,
    INITCAP(TRIM(TYPE)) AS CATEGORY,
    TRIM(DETAILS) AS DESCRIPTION,
    TRY_TO_DECIMAL(RETAIL_PRICE, 10, 2) AS PRICE,
    INITCAP(TRIM(COLOUR)) AS COLOR,
    UPPER(TRIM(DIMENSIONS)) AS SIZE,
    INITCAP(TRIM(FABRIC)) AS MATERIAL,
    CASE
        WHEN UPPER(TRIM(AVAILABILITY)) IN ('TRUE', 'YES', '1', 'IN STOCK', 'AVAILABLE')
        THEN TRUE
        WHEN UPPER(TRIM(AVAILABILITY)) IN ('FALSE', 'NO', '0', 'OUT OF STOCK', 'UNAVAILABLE')
        THEN FALSE
        ELSE NULL
    END AS IN_STOCK,
    TRY_TO_TIMESTAMP_NTZ(LAST_MODIFIED) AS UPDATED_AT,
    CURRENT_TIMESTAMP() AS PROCESSED_AT

FROM PRODUCT_CATALOG_DB.BRONZE.URBANTHREAD_RAW;




-- DATA VALIDATION
SELECT SOURCE_SYSTEM, COUNT(*) AS TOTAL
FROM PRODUCT_CATALOG_DB.SILVER.PRODUCTS_STANDARDIZED
GROUP BY SOURCE_SYSTEM;




-- CREATE MATCH TABLE
CREATE OR REPLACE VIEW PRODUCT_CATALOG_DB.SILVER.PRODUCT_MATCHING AS
SELECT
    SOURCE_SYSTEM,
    SOURCE_PRODUCT_ID,
    PRODUCT_NAME,
    BRAND,
    CATEGORY,
    DESCRIPTION,
    PRICE,
    COLOR,
    SIZE,
    MATERIAL,
    IN_STOCK,
    UPDATED_AT,

    LOWER(
        REGEXP_REPLACE(
            TRIM(PRODUCT_NAME),
            '[^a-zA-Z0-9 ]',
            ''
        )
    ) AS NORMALIZED_NAME,

    LOWER(TRIM(BRAND)) AS NORMALIZED_BRAND,

    LOWER(TRIM(CATEGORY)) AS NORMALIZED_CATEGORY

FROM PRODUCT_CATALOG_DB.SILVER.PRODUCTS_STANDARDIZED;



-- validate PRODUCTS_STANDARDIZED
SELECT
    SOURCE_SYSTEM,
    SOURCE_PRODUCT_ID,
    PRODUCT_NAME,
    NORMALIZED_NAME,
    BRAND,
    CATEGORY,
    PRICE,
    COLOR,
    SIZE
FROM PRODUCT_CATALOG_DB.SILVER.PRODUCT_MATCHING
ORDER BY NORMALIZED_NAME
LIMIT 20;




